// DEEPER — the miner. Hand-authored ASCII in the src/art/spritesheet.js format.
//
// Every frame is 24x30 with the anchor at (12, 29): horizontal centre, feet on the floor line.
// The 11x26 collision box sits inside columns 6..17 / rows 4..29 — the PICK deliberately
// breaks that box, because the tool leaving the body's footprint is what makes a swing read
// as a swing at 1x zoom.
//
// Light in DEEPER comes from the helmet lamp: front and slightly below. So highlights
// (CLOTH2 / HELM2 / SKIN2 / LEATH2) always sit on the FORWARD, LOWER side of a form, and the
// backs of things fall into CLOTH0 / HELM0 / INK. All frames face RIGHT; the renderer mirrors.
//
// Generated-by-hand note: the far leg uses derived darker shades of the trouser/boot colours so
// a side-on walk cycle reads which leg is leading — with one flat colour a 6-frame stride is
// invisible at this size.

import { P } from './pal.js';

function mix(a, b, t) {
  const x = parseInt(a.slice(1), 16), y = parseInt(b.slice(1), 16);
  const r = Math.round(((x >> 16) & 255) * (1 - t) + ((y >> 16) & 255) * t);
  const g = Math.round(((x >> 8) & 255) * (1 - t) + ((y >> 8) & 255) * t);
  const b2 = Math.round((x & 255) * (1 - t) + (y & 255) * t);
  return '#' + ((1 << 24) | (r << 16) | (g << 8) | b2).toString(16).slice(1);
}

// Derived (not invented): the limb on the far side of the body, pushed toward INK.
const CLOTH_FAR = mix(P.CLOTH0, P.INK, 0.45);
const LEATH_FAR = mix(P.LEATH0, P.INK, 0.40);

